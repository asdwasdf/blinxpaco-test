import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
if (process.env.PACO_ALLOW_MUTATION !== 'true') throw new Error('Blocked: PACO_ALLOW_MUTATION=true required');
const runId = `20260917-connect-files-${Date.now()}`;
const outDir = path.resolve(`test-results/PAC2-4700/execute/${runId}`);
await mkdir(outDir, { recursive: true });
const invalid = path.join(outDir, 'qa-invalid.exe');
const valid = path.join(outDir, 'qa-valid.txt');
await writeFile(invalid, 'Synthetic invalid extension; no executable content.\n');
await writeFile(valid, 'Synthetic valid file; no personal data.\n');
const browser = await chromium.connectOverCDP('http://127.0.0.1:9222');
const context = browser.contexts()[0];
const page = await context.newPage();
const result = { result: 'Inconclusive', files: {}, mutation: { class: 'Temporary', occurred: false }, cleanup: { required: true, performed: true, leftovers: [] }, errors: [] };
try {
  await page.goto('https://blinx.dev.blinxpaco-np.com/paco-connect/feature-branch/pac2-4700-qs-only/', { waitUntil: 'domcontentloaded', timeout: 60_000 });
  const search = page.getByPlaceholder(/Search(?: patients by name or NHS number)?(?:\.\.\.)?/i).first();
  await search.waitFor({ state: 'visible', timeout: 45_000 });
  await search.fill('Michael Ramella');
  const row = page.locator('div[class*="patient-row"]:visible').filter({ hasText: /Michael\s+Ramella|Ramella,\s*Michael/i }).first();
  await row.waitFor({ state: 'visible', timeout: 30_000 });
  const actions = row.getByRole('button', { name: 'Patient actions menu' });
  await actions.click({ timeout: 10_000 }).catch(async () => { await page.keyboard.press('Escape'); await actions.click({ force: true }); });
  const quick = page.getByRole('menuitem', { name: 'Quick Send', exact: true }).first();
  await quick.waitFor({ state: 'visible', timeout: 10_000 });
  await quick.click();
  const dialog = page.getByRole('dialog').filter({ has: page.getByRole('button', { name: 'quick-send-action' }) }).last();
  await dialog.waitFor({ state: 'visible', timeout: 30_000 });
  result.branchRetained = /paco-connect\/feature-branch\/pac2-4700-qs-only/i.test(page.url());
  await dialog.locator('button').filter({ hasText: /^\s*\d*\s*Files\s*$/i }).first().click();
  const input = dialog.locator('input[type="file"]').first();
  result.files.accept = await input.getAttribute('accept');
  await input.setInputFiles(invalid);
  result.mutation.occurred = true;
  const invalidLabel = dialog.getByText('qa-invalid.exe', { exact: true }).first();
  const toast = page.locator('.p-toast-message:visible').last();
  await Promise.race([invalidLabel.waitFor({ state: 'visible', timeout: 5_000 }).catch(() => {}), toast.waitFor({ state: 'visible', timeout: 5_000 }).catch(() => {})]);
  result.files.invalidRendered = await invalidLabel.isVisible().catch(() => false);
  result.files.invalidFeedbackVisible = await toast.isVisible().catch(() => false);
  await input.setInputFiles(valid);
  const validLabel = dialog.getByText('qa-valid.txt', { exact: true }).first();
  await validLabel.waitFor({ state: 'visible', timeout: 10_000 });
  result.files.validRendered = true;
  result.files.invalidRemoveControl = await invalidLabel.locator('xpath=ancestor::div[contains(@class,"added-attachment")][1]').locator('button:visible,[role="button"]:visible').count() > 0;
  result.files.validRemoveControl = await validLabel.locator('xpath=ancestor::div[contains(@class,"added-attachment")][1]').locator('button:visible,[role="button"]:visible').count() > 0;
  result.result = result.branchRetained && result.files.validRendered ? (result.files.invalidRendered || !result.files.invalidFeedbackVisible ? 'Fail' : 'Pass') : 'Inconclusive';
} catch (error) {
  result.errors.push(error.message.split('\n')[0]);
} finally {
  await page.close();
  result.cleanup.performed = true;
  result.cleanup.note = 'Draft discarded by closing page; no Save, Send Now, or Schedule action';
}
result.observedAt = new Date().toISOString();
await writeFile(path.join(outDir, 'connect-files.json'), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
await browser.close();
